#!/usr/bin/env node
/**
 * The public pages' stylesheet sources (runs in `predev` / `prebuild`).
 *
 * Tailwind scans the whole repository for the classes it must write, so one stylesheet carried the
 * utilities of every screen of the app (the editor, planning, the admin console…) to a visitor of the
 * home page, in the render-blocking CSS of its first paint. The public pages' sheet (src/styles/public.css)
 * scans only the files the public pages can reach: scripts/lib/public-css-sources.mjs follows the imports
 * from every route of the public site, and this writes the files as `@source` lines to
 * src/styles/public-sources.generated.css (committed like the other generated styles; regenerated on
 * every build).
 *
 * A route added under (site) is picked up by itself; so is a component a public page starts to import.
 * `npm run check:public-css` (scripts/check-public-css.mjs) proves it on a running build: every class the
 * public pages render is in their stylesheet.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { publicSourceFiles } from './lib/public-css-sources.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const styles = join(root, 'src', 'styles');
const files = publicSourceFiles(root).map((file) => relative(styles, file).split('\\').join('/'));
writeFileSync(
  join(styles, 'public-sources.generated.css'),
  `/* Generated by scripts/build-public-css.mjs — the files the public pages can reach (${files.length}). */\n` +
    files.map((file) => `@source "${file}";`).join('\n') +
    '\n',
);
console.log(`✓ public CSS sources: ${files.length} files → src/styles/public-sources.generated.css`);
